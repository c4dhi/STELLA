// Generates docs/changelog.md from the repository's CHANGELOG.md.
//
// There used to be two changelogs maintained by hand, and they drifted in both
// directions: the root file had the 1.1.0 release the site never got, the site
// had a page of entries the root file never got. release-please writes the root
// file, so that is the single source of truth and this page is derived from it.
//
// Runs automatically via the prebuild/prestart hooks in package.json. The
// generated page is gitignored -- edit ../CHANGELOG.md instead.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../CHANGELOG.md");
const target = resolve(here, "../docs/changelog.md");

const raw = readFileSync(source, "utf8");

// Drop the source file's own H1 and the boilerplate paragraph under it; the
// page below supplies its own title and framing.
const body = raw
  .replace(/^#\s+Changelog\s*\n/, "")
  .replace(
    /^All notable changes to STELLA will be documented in this file\.\s*\n+The format is based on[^\n]*\n[^\n]*\n/m,
    "",
  )
  .trim();

const page = `---
sidebar_position: 100
title: Changelog
description: Release history and notable changes
---

{/* GENERATED FILE -- do not edit. Source: CHANGELOG.md at the repository root.
    Regenerated by docs-site/scripts/sync-changelog.mjs on build. */}

# Changelog

All notable changes to STELLA are documented here, generated from
[CHANGELOG.md](https://github.com/c4dhi/STELLA/blob/main/CHANGELOG.md) in the
repository. The format follows
[Keep a Changelog](https://keepachangelog.com/en/1.1.0/), and STELLA uses
[Semantic Versioning](https://semver.org/spec/v2.0.0.html).

## Version Policy

Versions are derived from [Conventional Commit](https://www.conventionalcommits.org/)
types, so the release history reflects what actually changed:

- **Major (X.0.0)** — breaking changes to APIs or configuration (\`feat!\`, \`BREAKING CHANGE\`)
- **Minor (1.X.0)** — new features, backward compatible (\`feat\`)
- **Patch (1.1.X)** — bug fixes, backward compatible (\`fix\`)

The Agent SDK versions independently and is released to
[PyPI](https://pypi.org/project/stella-ai-agent-sdk/) on its own \`sdk-v*\` tags —
see its
[changelog](https://github.com/c4dhi/STELLA/blob/main/agents/stella-ai-agent-sdk/CHANGELOG.md).

${body}
`;

writeFileSync(target, page);
console.log(`sync-changelog: wrote ${target} from ${source}`);
